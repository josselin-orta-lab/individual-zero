"""Synthetic signed-witness contract only: no real signer or independent M11."""
from dataclasses import replace
from pathlib import Path
import sys
import unittest

sys.path.insert(0,str(Path(__file__).resolve().parents[2]/"src"))
from i2.modules.challenge_witness_contract import (
    SCHEMA, TrustPolicy, SignedClaim, verify_claim, canonical,
)
from i2.modules.lifecycle_external_witness import LatestWitness,WITNESS_SCHEMA,LIFECYCLE_SCHEMA,ZERO_HASH

CHALLENGE="a"*64
RECORD=LatestWitness(WITNESS_SCHEMA,"life:synthetic","genesis:synthetic",LIFECYCLE_SCHEMA,
                     0,-1,ZERO_HASH,None,None,"proof:synthetic")
POLICY=TrustPolicy("authority:test","key:test",10,1000)

class MockVerifier:
    def __init__(self, result=True):
        self.result=result
        self.calls=[]
    def verify(self, **kwargs):
        self.calls.append(kwargs)
        return self.result

def claim():
    return SignedClaim(SCHEMA,POLICY.authority_ref,POLICY.key_ref,CHALLENGE,100,150,
                       RECORD,b"test-signature-not-cryptography")

class ContractTests(unittest.TestCase):
    def check_rejected(self, c, p=POLICY, challenge=CHALLENGE, now=110):
        v=MockVerifier()
        with self.assertRaises(ValueError):
            verify_claim(claim=c,policy=p,challenge=challenge,now=now,verifier=v)
        self.assertEqual(v.calls,[])

    def test_valid_declared_proof_has_no_motor_or_recovery_authority(self):
        v=MockVerifier()
        self.assertEqual(verify_claim(claim=claim(),policy=POLICY,
                                      challenge=CHALLENGE,now=110,verifier=v),RECORD)
        self.assertEqual(len(v.calls),1)
        self.assertIs(type(v.calls[0]["message"]),bytes)

    def test_wrong_nonce_key_authority_and_revocation_fail_before_verifier(self):
        self.check_rejected(replace(claim(),challenge="b"*64))
        self.check_rejected(replace(claim(),key_ref="key:other"))
        self.check_rejected(replace(claim(),authority_ref="authority:other"))
        self.check_rejected(claim(),p=replace(POLICY,revoked=True))
        self.check_rejected(claim(),challenge="b"*64)

    def test_time_window_and_nonboolean_clock_are_rejected(self):
        for now in (-1,True,99,150,2000):
            self.check_rejected(claim(),now=now)
        self.check_rejected(replace(claim(),issued_at=True))
        self.check_rejected(replace(claim(),expires_at=2000))
        self.check_rejected(replace(claim(),issued_at=9))
        self.check_rejected(claim(),p=replace(POLICY,valid_until=120))

    def test_malformed_record_and_signature_are_rejected(self):
        self.check_rejected(replace(claim(),record=replace(RECORD,life_ref="")))
        self.check_rejected(replace(claim(),signature=b""))
        self.check_rejected(replace(claim(),signature="not bytes"))
        self.check_rejected(replace(claim(),schema="legacy"))

    def test_explicit_false_or_truthy_nonboolean_verifier_is_not_accepted(self):
        for result in (False,1,"true",None):
            v=MockVerifier(result)
            with self.subTest(result=result),self.assertRaises(ValueError):
                verify_claim(claim=claim(),policy=POLICY,challenge=CHALLENGE,
                             now=110,verifier=v)
        self.assertEqual(canonical({"b":1,"a":2}),b'{"a":2,"b":1}')

    def test_later_claim_or_replayed_valid_signature_is_not_latest_proof(self):
        # A successful injected verifier proves only its claimed payload.
        # No monotonic oracle is deployed here, and an independently fresh
        # challenge MUST be generated by a real caller for every request.
        v=MockVerifier()
        self.assertEqual(verify_claim(claim=claim(),policy=POLICY,
                                      challenge=CHALLENGE,now=110,verifier=v),RECORD)
        self.assertEqual(verify_claim(claim=claim(),policy=POLICY,
                                      challenge=CHALLENGE,now=110,verifier=v),RECORD)
        self.assertEqual(len(v.calls),2)

if __name__=="__main__":
    unittest.main()
